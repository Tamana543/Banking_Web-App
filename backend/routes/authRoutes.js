import express from "express";
import protect from "../middleware/authMiddleware.js";
import verifyPin from "../middleware/pinMiddleware.js";
import pinRateLimiter from "../middleware/pinRateLimiter.js";
import { registerUser, loginUser, getCurrentUser, logoutUser, updateProfile, changePassword, changePin, updateDisplayCurrency, deleteAccount } from "../controllers/authController.js";
import { uploadAvatar } from "../controllers/uploadController.js";
import upload from "../middleware/uploadMiddleware.js";
import { loginRateLimiter, registerRateLimiter,passwordChangeRateLimiter } from "../middleware/authRateLimiter.js";
const router = express.Router();
router.post("/register", registerRateLimiter, registerUser);
router.post("/login", loginRateLimiter, loginUser);
router.get( "/me", protect, getCurrentUser );
router.post( "/logout", protect, logoutUser );
router.post( "/avatar", protect, upload.single("avatar"), uploadAvatar );
router.put( "/profile", protect, updateProfile );
router.put( "/change-password", protect, passwordChangeRateLimiter,changePassword );
router.put( "/change-pin", protect, pinRateLimiter, verifyPin("currentPin"), changePin );
router.put( "/currency", protect, updateDisplayCurrency );
router.post( "/delete-account", protect, pinRateLimiter, passwordChangeRateLimiter, verifyPin(), deleteAccount );
export default router;